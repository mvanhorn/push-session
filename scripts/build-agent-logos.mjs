// Renders the agent logos to small PNGs for terminals that can draw images, and writes
// src/agent-logos.js. Run by hand when a logo changes; needs `rsvg-convert` (librsvg).
import { execFileSync } from "node:child_process";
import fs from "node:fs";

import { PROVIDER_LOGOS } from "../vendor/t3code-viewer/t3/providerLogos.js";

const SIZE = 64;
// Logos drawn in the text colour need one version per terminal background.
const INK = { dark: "#f5f5f5", light: "#18181b" };

function png(logo, fill) {
  const [x, y, width, height] = logo.viewBox.split(" ").map(Number);
  // Centre the logo in a square with a little air, so it is not stretched into the cell box.
  const side = Math.max(width, height) * 1.12;
  const viewBox = [x - (side - width) / 2, y - (side - height) / 2, side, side].join(" ");
  const rule = logo.evenOdd ? ' fill-rule="evenodd" clip-rule="evenodd"' : "";
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${SIZE}" height="${SIZE}">${logo.paths.map((path) => `<path d="${path.d || path}" fill="${path.fill || fill}"${rule}/>`).join("")}</svg>`;
  return execFileSync("rsvg-convert", ["-f", "png"], { input: svg }).toString("base64");
}

const logos = {};
for (const [agent, logo] of Object.entries(PROVIDER_LOGOS)) {
  const ownColours = logo.fill || logo.paths.every((path) => path.fill);
  logos[agent] = ownColours ? { any: png(logo, logo.fill) } : { dark: png(logo, INK.dark), light: png(logo, INK.light) };
}
const source = `// Generated by scripts/build-agent-logos.mjs. Do not edit.\n// Base64 PNGs, ${SIZE}px square. "dark" and "light" name the terminal background they are for.\nexport const AGENT_LOGO_PNGS = ${JSON.stringify(logos, null, 2)};\n`;
fs.writeFileSync(new URL("../src/agent-logos.js", import.meta.url), source);
console.log(Object.entries(logos).map(([agent, set]) => `${agent}: ${Object.values(set).map((data) => `${Math.round(data.length * 0.75)}B`).join(", ")}`).join("  "));
